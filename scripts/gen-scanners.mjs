// Generates the barcode-scanner section from scripts/scanners/data.mjs:
//   {,ca/,eu/,gl/}lectores/index.html             one index per language
//   {,ca/,eu/,gl/}lectores/<slug>/index.html      one page per scanner
//   public/lectores/pdf/<slug>-<lang>.pdf         printable sheet per scanner
// The configuration codes are inline SVG in the pages (crisp at any zoom, no
// image requests) and vector paths in the PDFs. All outputs are committed, like
// the FAQ shells: run `npm run gen:scanners` after editing data.mjs.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import bwipjs from 'bwip-js';
import fontkit from '@pdf-lib/fontkit';
import { PDFDocument, rgb } from 'pdf-lib';
import { LANGS, SCANNERS, T } from './scanners/data.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://nuncaeslupus.github.io/farma-kit/';
// Vite rewrites asset URLs (img, css) to the base, but not plain <a href>s.
const BASE = '/farma-kit/';
const OG_LOCALE = { es: 'es_ES', ca: 'ca_ES', eu: 'eu_ES', gl: 'gl_ES' };
const OG_IMAGE = { es: 'og-card.png', ca: 'og-card-ca.png', eu: 'og-card-eu.png', gl: 'og-card-gl.png' };

const prefix = (lang) => (lang === 'es' ? '' : `${lang}/`);
const indexPath = (lang) => `${prefix(lang)}lectores/`;
const pagePath = (lang, s) => `${indexPath(lang)}${s.slug}/`;
const pdfName = (lang, s) => `${s.slug}-${lang}.pdf`;

const esc = (str) =>
  String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/* ---------- barcodes ---------- */

function barcodeSvg(code) {
  const opts = { bcid: code.bcid, text: code.data, scale: 1 };
  // bwip-js UTF-8-encodes chars above 0x7F; the scanner wants the raw byte
  // (e.g. Tera's \x80 prefix), so pass those through its ^NNN byte escape.
  if (/[^\x00-\x7f]/.test(code.data)) {
    opts.text = code.data.replace(/[\^\x80-\xff]/g, (c) => `^${String(c.charCodeAt(0)).padStart(3, '0')}`);
    opts.parse = true;
  }
  if (code.bcid === 'code128') opts.height = 12; // mm-ish at scale 1 → 35 units
  return bwipjs.toSVG(opts);
}

/** Inline SVG for the page: drop the fixed size, keep the viewBox, size by CSS. */
function inlineBarcode(code) {
  const svg = barcodeSvg(code);
  // Every code gets the same box: linear codes are stretched to one fixed
  // width × height (only the module width changes, ≥1.6 px), QR codes to one
  // fixed square — so all steps line up regardless of payload length.
  const qr = code.bcid === 'qrcode';
  const [width, height] = qr ? [120, 120] : [280, 80];
  return svg.replace(
    '<svg ',
    `<svg class="code-svg${qr ? ' code-svg--qr' : ''}" width="${width}" height="${height}" preserveAspectRatio="none" role="img" aria-label="${esc(
      qr ? 'QR' : code.data,
    )}" shape-rendering="crispEdges" `,
  );
}

/* ---------- HTML ---------- */

function head({ lang, title, desc, path, alternates, jsonLd }) {
  const alt = LANGS.map(
    (l) => `    <link rel="alternate" hreflang="${l}" href="${SITE}${alternates(l)}" />`,
  ).join('\n');
  return `<!doctype html>
<!-- GENERATED by scripts/gen-scanners.mjs from scripts/scanners/data.mjs — do not edit by hand. -->
<html lang="${lang}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
    <link rel="preload" href="/fonts/space-grotesk-latin-600-normal.woff2" as="font" type="font/woff2" crossorigin />
    <link rel="preload" href="/fonts/ibm-plex-sans-latin-400-normal.woff2" as="font" type="font/woff2" crossorigin />
    <meta name="theme-color" content="#f4efe6" />
    <title>${esc(title)} — FarmaKit</title>
    <meta name="description" content="${esc(desc)}" />
    <link rel="canonical" href="${SITE}${path}" />
${alt}
    <link rel="alternate" hreflang="x-default" href="${SITE}${alternates('es')}" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="FarmaKit" />
    <meta property="og:url" content="${SITE}${path}" />
    <meta property="og:title" content="${esc(title)} — FarmaKit" />
    <meta property="og:description" content="${esc(desc)}" />
    <meta property="og:image" content="${SITE}${OG_IMAGE[lang]}" />
    <meta property="og:locale" content="${OG_LOCALE[lang]}" />
    <meta name="twitter:card" content="summary_large_image" />${
      jsonLd
        ? `\n    <script type="application/ld+json">\n${JSON.stringify(jsonLd, null, 2)
            .split('\n')
            .map((l) => `      ${l}`)
            .join('\n')}\n    </script>`
        : ''
    }
  </head>`;
}

const shell = (main) => `
  <body class="faqPage scanPage">
    <div class="faqShell">
      <div id="faqTop"></div>
      <main class="faqMain scanMain">
${main}
      </main>
      <div id="faqBottom"></div>
    </div>
    <script type="module" src="/src/lectores.ts"></script>
  </body>
</html>
`;

function indexHtml(lang) {
  const t = T[lang];
  const cards = SCANNERS.map(
    (s) => `        <a class="scanCard" href="${s.slug}/">
          <img class="scanCard-img" src="/lectores/img/${s.img}" alt="" width="640" height="640" />
          <span class="scanCard-body">
            <span class="scanCard-brand">${esc(s.brand)}</span>
            <span class="scanCard-model">${esc(s.model)}</span>
            <span class="scanCard-tag">${esc(t.tested)}</span>
            <span class="scanCard-go">${esc(t.seeConfig)} →</span>
          </span>
        </a>`,
  ).join('\n');
  const faq = t.faq
    .map(([q, a]) => `        <section>\n          <h3>${esc(q)}</h3>\n          <p>${esc(a)}</p>\n        </section>`)
    .join('\n');
  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    inLanguage: lang,
    mainEntity: t.faq.map(([q, a]) => ({
      '@type': 'Question',
      name: q,
      acceptedAnswer: { '@type': 'Answer', text: a },
    })),
  };
  return (
    head({
      lang,
      title: t.indexTitle,
      desc: t.indexDesc,
      path: indexPath(lang),
      alternates: indexPath,
      jsonLd,
    }) +
    shell(`        <h1>${esc(t.indexTitle)}</h1>
        <p class="scanLead">${t.indexIntro}</p>
        <div class="scanCards">
${cards}
        </div>
        <h2 id="faq" class="scanH2">${esc(t.faqTitle)}</h2>
        <div class="scanFaq">
${faq}
        </div>`)
  );
}

function stepHtml(code, n, t) {
  const [title, desc] = t.s[code.key];
  const payload = code.bcid === 'code128' ? `<code class="code-text">${esc(code.data)}</code>` : '';
  return `          <li class="scanStep">
            <div class="scanStep-text">
              <span class="scanStep-n">${esc(n)}</span>
              <div>
                <h3>${esc(title)}</h3>
                <p>${esc(desc)}</p>
              </div>
            </div>
            <figure class="scanStep-code">${inlineBarcode(code)}${payload}</figure>
          </li>`;
}

function pageHtml(lang, s) {
  const t = T[lang];
  const steps = s.steps.map((c, i) => stepHtml(c, String(i + 1), t)).join('\n');
  const options = s.options.length
    ? `
        <h2 class="scanH2">${esc(t.optionsTitle)}</h2>
        <ol class="scanSteps scanSteps--opt">
${s.options.map((c) => stepHtml(c, '·', t)).join('\n')}
        </ol>`
    : '';
  const links = s.links
    .map((l) => `          <li><a href="${esc(l.href)}" target="_blank" rel="noopener">${esc(t.linkLabels[l.key])}</a></li>`)
    .join('\n');
  return (
    head({
      lang,
      title: t.pageTitle(s),
      desc: t.pageDesc(s),
      path: pagePath(lang, s),
      alternates: (l) => pagePath(l, s),
    }) +
    shell(`        <a class="faqBack" href="../">${esc(t.back)}</a>
        <div class="scanHero">
          <img src="/lectores/img/${s.img}" alt="${esc(`${s.brand} ${s.model}`)}" width="640" height="640" />
          <div>
            <h1>${esc(t.pageTitle(s))}</h1>
            <p class="scanId">${esc(t.identifyLabel)} <code>${esc(s.partNo)}</code></p>
            <p class="scanTag">${esc(t.tested)}</p>
            <a class="scanPdf" href="${BASE}lectores/pdf/${pdfName(lang, s)}" download>
              <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"></path><polyline points="7 10 12 15 17 10"></polyline><line x1="12" y1="15" x2="12" y2="3"></line></svg>
              ${esc(t.pdf)}
            </a>
          </div>
        </div>
        <h2 class="scanH2">${esc(t.steps)}</h2>
        <p class="scanLead">${esc(t.howTo)} <span class="scanTip">${esc(t.screenTip)}</span></p>
        <ol class="scanSteps">
${steps}
        </ol>
        <div class="scanCheck">
          <h3>${esc(t.check)}</h3>
          <p>${esc(t.checkText)}</p>
        </div>${options}
        <h2 class="scanH2">${esc(t.links)}</h2>
        <ul class="scanLinks">
${links}
        </ul>`)
  );
}

/* ---------- PDF ---------- */

const A4 = [595.28, 841.89];
const M = 48;
const INK = rgb(0.125, 0.114, 0.094);
const MUTED = rgb(0.427, 0.4, 0.353);
const ACCENT = rgb(0.059, 0.365, 0.361);
const LINE = rgb(0.867, 0.835, 0.776);

function wrap(text, font, size, width) {
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    const next = line ? `${line} ${word}` : word;
    if (line && font.widthOfTextAtSize(next, size) > width) {
      lines.push(line);
      line = word;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}

/** Draw a bwip-js SVG into the box (x, top, width, height). */
function drawBarcode(page, code, x, top, width, height) {
  const svg = barcodeSvg(code);
  const [, w, h] = /viewBox="0 0 (\d+) (\d+)"/.exec(svg).map(Number);
  const k = width / w;
  const ky = height / h;
  for (const m of svg.matchAll(/<path ([^>]*?)d="([^"]+)"/g)) {
    const sw = /stroke-width="([\d.]+)"/.exec(m[1]);
    if (sw) {
      // Linear codes: each bar is a vertical stroke "Mx y1Lx y2".
      for (const bar of m[2].matchAll(/M([\d.]+) ([\d.]+)L[\d.]+ ([\d.]+)/g)) {
        const cx = +bar[1];
        const y1 = Math.min(+bar[2], +bar[3]);
        const y2 = Math.max(+bar[2], +bar[3]);
        page.drawRectangle({
          x: x + (cx - +sw[1] / 2) * k,
          y: top - y2 * ky,
          width: +sw[1] * k,
          height: (y2 - y1) * ky,
          color: rgb(0, 0, 0),
        });
      }
    } else {
      page.drawSvgPath(m[2], { x, y: top, scale: k, color: rgb(0, 0, 0) });
    }
  }
}

async function buildPdf(lang, s, fonts) {
  const t = T[lang];
  const doc = await PDFDocument.create();
  doc.registerFontkit(fontkit);
  const [reg, bold, mono] = await Promise.all(fonts.map((b) => doc.embedFont(b, { subset: true })));
  doc.setTitle(`${t.pageTitle(s)} — FarmaKit`);
  doc.setAuthor('FarmaKit');
  doc.setLanguage(lang);
  // Fixed dates keep regenerated PDFs byte-stable when nothing changed.
  doc.setCreationDate(new Date('2026-10-14T00:00:00Z'));
  doc.setModificationDate(new Date('2026-10-14T00:00:00Z'));

  const textW = A4[0] - 2 * M - 230;
  let page;
  let y;
  const newPage = () => {
    page = doc.addPage(A4);
    y = A4[1] - M;
    page.drawText(`FarmaKit · ${t.indexShort}`, { x: M, y: y - 9, size: 9, font: reg, color: MUTED });
    page.drawText(`${SITE}${pagePath(lang, s)}`, { x: M, y: M / 2, size: 8, font: reg, color: MUTED });
    y -= 26;
  };
  const para = (text, font, size, color, width = A4[0] - 2 * M, gap = 4) => {
    for (const l of wrap(text, font, size, width)) {
      page.drawText(l, { x: M, y: y - size, size, font, color });
      y -= size + gap;
    }
  };
  newPage();
  para(t.pageTitle(s), bold, 18, INK);
  para(`${t.identifyLabel} ${s.partNo}`, reg, 10, MUTED);
  y -= 6;
  para(t.howTo, reg, 11, INK);
  y -= 10;

  const row = (code, n) => {
    const [title, desc] = t.s[code.key];
    const isQr = code.bcid === 'qrcode';
    // Same frame for every code (see inlineBarcode): fixed-size bars or square.
    const FW = 200;
    const FH = 92;
    const titleLines = wrap(title, bold, 12, textW - 30);
    const descLines = wrap(desc, reg, 9.5, textW - 30);
    const textH = titleLines.length * 16 + descLines.length * 13;
    const codeH = FH;
    const h = Math.max(textH, codeH) + 24;
    if (y - h < M + 10) newPage();
    page.drawLine({ start: { x: M, y }, end: { x: A4[0] - M, y }, thickness: 0.6, color: LINE });
    let ty = y - 14;
    page.drawText(n, { x: M, y: ty - 12, size: 14, font: bold, color: ACCENT });
    for (const l of titleLines) {
      page.drawText(l, { x: M + 30, y: ty - 12, size: 12, font: bold, color: INK });
      ty -= 16;
    }
    for (const l of descLines) {
      page.drawText(l, { x: M + 30, y: ty - 10, size: 9.5, font: reg, color: MUTED });
      ty -= 13;
    }
    const fx = A4[0] - M - FW;
    const fy = y - 12;
    page.drawRectangle({ x: fx, y: fy - FH, width: FW, height: FH, borderColor: LINE, borderWidth: 0.8 });
    if (isQr) {
      const q = 74;
      drawBarcode(page, code, fx + (FW - q) / 2, fy - (FH - q) / 2, q, q);
    } else {
      const bw = 176;
      const bh = 52;
      drawBarcode(page, code, fx + (FW - bw) / 2, fy - 12, bw, bh);
      const tw = mono.widthOfTextAtSize(code.data, 8);
      page.drawText(code.data, { x: fx + (FW - tw) / 2, y: fy - 12 - bh - 13, size: 8, font: mono, color: MUTED });
    }
    y -= h;
  };
  s.steps.forEach((c, i) => row(c, String(i + 1)));
  y -= 8;
  if (y < M + 80) newPage();
  para(t.check, bold, 12, INK);
  para(t.checkText, reg, 10, MUTED);
  if (s.options.length) {
    y -= 14;
    if (y < M + 120) newPage();
    para(t.optionsTitle, bold, 14, INK);
    y -= 4;
    s.options.forEach((c) => row(c, '·'));
  }
  return doc.save({ useObjectStreams: false });
}

/* ---------- main ---------- */

function write(rel, content) {
  const abs = join(ROOT, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, content);
}

const font = (f) => readFileSync(join(ROOT, 'public/fonts', f));
const fonts = [
  font('ibm-plex-sans-latin-400-normal.woff'),
  font('ibm-plex-sans-latin-700-normal.woff'),
  font('ibm-plex-mono-latin-400-normal.woff'),
];

for (const lang of LANGS) {
  write(`${indexPath(lang)}index.html`, indexHtml(lang));
  for (const s of SCANNERS) {
    write(`${pagePath(lang, s)}index.html`, pageHtml(lang, s));
    write(`public/lectores/pdf/${pdfName(lang, s)}`, await buildPdf(lang, s, fonts));
  }
}
console.log(`scanners: ${LANGS.length} × (1 index + ${SCANNERS.length} pages + ${SCANNERS.length} PDFs)`);
